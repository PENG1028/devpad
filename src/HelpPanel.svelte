 <h3>开始使用</h3>
 <p>直接记录文字、粘贴截图或拖入图片。新笔记默认是普通笔记，可稍后移动和加标签。</p>
 <h3>复制与完整导出</h3>
 <p>笔记右上角的复制按钮只复制正文。下拉菜单可以复制图片，或打开模板与导出预览。多选也使用同一套模板。</p>
 <p>“原文”不会附加状态和执行指令。图文资料会包含图片对应关系；完整导出保留全部图片和清单。目标软件是否支持同时粘贴多图，由其输入框决定。</p>
 <h3>草稿与更新</h3>
 <p>输入会自动存为本地草稿。关闭编辑窗口后可从“恢复草稿”继续；点击保存会正式保存笔记。更新前保存草稿并备份数据库。</p>
 <p>开发版用于测试新功能，稳定版用于正式发布。后续更新沿用安装位置。旧的独立 EXE 需要先迁移到固定安装版。</p>
 <h3>Agent 与 MCP</h3>
 <p>设置中可复制本机 MCP 配置。普通笔记保持独立；从笔记菜单或多选栏发布任务后，agent 可以领取、读取原图并回写完成结果。更新时先断开 MCP 连接，完成后重连。</p>
 <h3>快捷键</h3>
 <p>Ctrl+N 新建；Ctrl+Enter 保存；Ctrl+F 搜索；Shift+点击连续选择。输入框外 Ctrl+A 全选当前结果。</p>
 <h3>数据与许可</h3>
 <p>笔记与图片保存在本机。数据位置见设置；备份时应保留数据库与附件目录。</p>
